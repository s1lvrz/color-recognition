"""### Closest Colour Match"""

def get_colour_name(red, green, blue, colour_data):
    """Return the closest colour class name based on RGB distance."""
    minimum_distance = float("inf")
    closest_colour = "Unknown"

    for i in range(len(colour_data)):
        distance = (
            abs(red - int(colour_data.loc[i, "R"]))
            + abs(green - int(colour_data.loc[i, "G"]))
            + abs(blue - int(colour_data.loc[i, "B"]))
        )

        if distance <= minimum_distance:
            minimum_distance = distance
            closest_colour = colour_data.loc[i, "color_name"]

    return closest_colour

"""### Colour Picker"""

class ColourPicker:
    """Tracks the last double-clicked pixel and draws an info bar for it."""

    def __init__(self, colour_data):
        self.colour_data = colour_data
        self.clicked = False
        self.r = self.g = self.b = 0
        self.xpos = self.ypos = 0

    def draw_function(self, event, x, y, flags, param):
        """Mouse callback: param is a dict holding the current image under 'image'."""
        if event == cv2.EVENT_LBUTTONDBLCLK:
            image = param["image"]
            if image is None:
                return

            self.clicked = True
            self.xpos, self.ypos = x, y
            b, g, r = image[y, x]
            self.b, self.g, self.r = int(b), int(g), int(r)

    def annotate(self, display_image):
        """Draw the colour swatch + label onto a copy of the image, if a click has happened."""
        if self.clicked:
            colour_name = get_colour_name(self.r, self.g, self.b, self.colour_data)
            text = f"{colour_name} R={self.r} G={self.g} B={self.b}"

            cv2.rectangle(display_image, (20, 20), (850, 60), (self.b, self.g, self.r), -1)

            text_colour = (255, 255, 255)
            if self.r + self.g + self.b >= 600:
                text_colour = (0, 0, 0)

            cv2.putText(
                display_image,
                text,
                (50, 50),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.8,
                text_colour,
                2,
                cv2.LINE_AA,
            )

        return display_image

