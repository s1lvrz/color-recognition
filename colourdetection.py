from google.colab.patches import cv2_imshow

def run_image_mode(colour_data, image_path):
    """Colab-friendly colour detection: enter pixel coordinates instead of clicking (no GUI window support in Colab)."""
    if not os.path.exists(image_path):
        raise FileNotFoundError(f"Image file not found: {image_path}")

    image = cv2.imread(image_path)
    if image is None:
        raise ValueError("Could not read image. Check the file format or path.")

    picker = ColourPicker(colour_data)
    height, width = image.shape[:2]

    print(f"Image size: {width} x {height} (width x height)")
    print("Enter pixel coordinates to sample a colour, or type 'q' to quit.\n")

    cv2_imshow(image)

    while True:
        user_input = input("Enter 'x,y' coordinates (or 'q' to quit): ").strip()

        if user_input.lower() == "q":
            break

        try:
            x_str, y_str = user_input.split(",")
            x, y = int(x_str.strip()), int(y_str.strip())
        except ValueError:
            print("Please enter coordinates in the form: x,y (e.g. 120,340)")
            continue

        if not (0 <= x < width and 0 <= y < height):
            print(f"Coordinates out of bounds. Must be within 0-{width - 1}, 0-{height - 1}.")
            continue

        # Reuse the existing mouse-callback logic by simulating a double-click at (x, y)
        picker.draw_function(cv2.EVENT_LBUTTONDBLCLK, x, y, None, {"image": image})
        display_image = picker.annotate(image.copy())

        colour_name = get_colour_name(picker.r, picker.g, picker.b, colour_data)
        print(f"Colour at ({x}, {y}): {colour_name} (R={picker.r}, G={picker.g}, B={picker.b})")

        cv2_imshow(display_image)

