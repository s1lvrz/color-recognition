"""### Locating the class folders"""

KNOWN_CLASSES = {"black", "blue", "brown", "green", "grey", "gray",
                  "orange", "red", "violet", "white", "yellow"}


def find_class_root(base_path, known_classes=KNOWN_CLASSES, min_matches=5):
    """Search base_path for the directory that holds the colour-class subfolders."""
    for root, dirs, _files in os.walk(base_path):
        dir_names = {d.lower() for d in dirs}
        if len(dir_names & known_classes) >= min_matches:
            return root
    return base_path


