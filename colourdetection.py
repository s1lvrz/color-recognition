"""### Building Colour Profiles from the Image Dataset

For each class folder, average the mean colour of every sample image to get one representative
(R, G, B) value per class.
"""

def build_colour_profiles(class_root):
    """Compute an average R/G/B profile for each colour class folder."""
    profiles = []
    image_exts = (".jpg", ".jpeg", ".png", ".bmp")

    class_dirs = sorted(
        d for d in os.listdir(class_root) if os.path.isdir(os.path.join(class_root, d))
    )

    for class_name in class_dirs:
        class_dir = os.path.join(class_root, class_name)
        image_files = [f for f in os.listdir(class_dir) if f.lower().endswith(image_exts)]

        r_sum = g_sum = b_sum = 0.0
        counted = 0

        for filename in image_files:
            img = cv2.imread(os.path.join(class_dir, filename))
            if img is None:
                continue

            b_mean, g_mean, r_mean = cv2.mean(img)[:3]
            r_sum += r_mean
            g_sum += g_mean
            b_sum += b_mean
            counted += 1

        if counted == 0:
            print(f"Warning: no readable images found for class '{class_name}', skipping.")
            continue

        profiles.append(
            {
                "color_name": class_name,
                "R": r_sum / counted,
                "G": g_sum / counted,
                "B": b_sum / counted,
            }
        )

    return pd.DataFrame(profiles)


